function showTopicQuestions(id){
 const box=document.getElementById("q-"+id);
 const qs=questions.filter(q=>q.t===id);
 if(!qs.length){box.innerHTML="<p class='small-note'>Todavía no hay preguntas específicas cargadas para este tema.</p>";return;}
 box.innerHTML=`<h3>Preguntas de ${topics.find(t=>t.id===id).name}</h3>`+qs.map((q,n)=>
 `<div class="mini-question"><strong>${n+1}. ${q.q}</strong><details><summary>Ver respuesta</summary><p>✅ ${q.a[q.c]}<br>${q.e}</p></details></div>`).join("");
}
function startTopicQuiz(id){showSection("quiz");topicFilter=id;current=0;loadTopicQuestion();}
let topicFilter=null;
function loadTopicQuestion(){
 const list=topicFilter?questions.filter(q=>q.t===topicFilter):questions;
 if(!list.length){topicFilter=null;renderQuiz();return;}
 current=Math.min(current,list.length-1);
 renderQuiz(list);
}
