document.getElementById("topicSearch").addEventListener("input",e=>renderTopics(e.target.value));

function renderQuiz(list=null){
 const pool=list || (topicFilter?questions.filter(q=>q.t===topicFilter):questions);
 const q=pool[current % pool.length];
 document.getElementById("progressBar").style.width=((current+1)/pool.length*100)+"%";
 document.getElementById("quizCard").innerHTML=`
 <span class="tag">${topicFilter?(topics.find(t=>t.id===topicFilter)?.name||"Tema"):"Repaso general"} · Pregunta ${current+1} de ${pool.length}</span>
 <h2>${q.q}</h2>
 <div class="answers">${q.a.map((x,i)=>`<button class="answer" onclick="answer(${i})">${String.fromCharCode(65+i)}. ${x}</button>`).join("")}</div>
 <div id="feedback"></div>`;
 answered=false;
}
function answer(i){
 if(answered)return;
 answered=true;
 const pool=topicFilter==="__exam20"?examPool:(topicFilter?questions.filter(q=>q.t===topicFilter):questions);
 const q=pool[current % pool.length];
 document.querySelectorAll(".answer").forEach((b,n)=>{if(n===q.c)b.classList.add("correct");if(n===i&&i!==q.c)b.classList.add("wrong")});
 if(i===q.c){score++;document.getElementById("scoreHome").textContent=score}
 document.getElementById("feedback").innerHTML=`<div class="explanation"><strong>${i===q.c?"✅ Correcto":"❌ Incorrecto"}</strong><br>${q.e}<br><br><button class="primary" onclick="nextQuestion()">Siguiente →</button></div>`;
}
function nextQuestion(){
 const pool=topicFilter==="__exam20"?examPool:(topicFilter?questions.filter(q=>q.t===topicFilter):questions);
 current=(current+1)%pool.length;
 renderQuiz(pool);
}
